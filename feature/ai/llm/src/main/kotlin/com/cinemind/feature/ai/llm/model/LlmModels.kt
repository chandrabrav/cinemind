package com.cinemind.feature.ai.llm.model

data class ChatMessage(
    val role: Role,
    val content: String,
    val timestamp: Long = System.currentTimeMillis()
)

enum class Role {
    SYSTEM, USER, ASSISTANT
}

data class ChatRequest(
    val messages: List<ChatMessage>,
    val maxTokens: Int = 2048,
    val temperature: Float = 0.7f,
    val stream: Boolean = false
)

data class ChatResponse(
    val content: String,
    val usage: UsageInfo,
    val finishReason: String
)

data class UsageInfo(
    val promptTokens: Int,
    val completionTokens: Int,
    val totalTokens: Int
)

sealed class LLMState {
    object Idle : LLMState()
    object Loading : LLMState()
    class Success(val response: ChatResponse) : LLMState()
    class Error(val exception: Throwable) : LLMState()
    class Streaming(val chunk: String, val isComplete: Boolean) : LLMState()
}

/**
 * Editing plan generated by the LLM, to be applied to the timeline.
 */
data class EditingPlan(
    val title: String,
    val description: String,
    val clips: List<PlanClip>,
    val transitions: List<PlanTransition>,
    val audio: PlanAudio?,
    val colorGrading: PlanColorGrading?,
    val estimatedDurationMs: Long
)

data class PlanClip(
    val sourceAssetId: String,
    val timelineStartMs: Long,
    val durationMs: Long,
    val sourceInMs: Long,
    val sourceOutMs: Long,
    val transitionIn: PlanTransition?,
    val transitionOut: PlanTransition?
)

data class PlanTransition(
    val type: String,
    val durationMs: Long
)

data class PlanAudio(
    val backgroundMusicId: String?,
    val volume: Float,
    val fadeInMs: Long,
    val fadeOutMs: Long
)

data class PlanColorGrading(
    val preset: String?,
    val exposure: Float,
    val contrast: Float,
    val saturation: Float,
    val temperature: Float
)