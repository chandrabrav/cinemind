enum class LutSource(val label: String) { BUILTIN("CineMind"), IMPORTED("Imported"), PACK("Film pack") }

/** A look in the library, from any source. */
data class LutEntry(
    val id: String,
    val name: String,
    val category: String,
    val tags: Set<String>,
    val source: LutSource,
    val description: String = "",
    /** False for a pack LUT not downloaded yet (tapping downloads it, ~130 KB). */
    val available: Boolean = true,
) {
    fun candidate() = LutCandidate(id, name, category, tags)
}

/** The optional community pack, described by an asset generated from a pinned commit. */
data class LutPackInfo(val name: String, val repo: String, val commit: String, val license: String)

/**
 * All looks CineMind can apply:
 * - **CineMind looks** — generated by the app (original, offline, always free to export);
 * - **Imported** — `.cube` files the user picked, validated and kept in app storage;
 * - **Film pack** — the G'MIC film LUT collection, catalogued in the app and downloaded one LUT
 *   at a time on request from a pinned commit, verified by its git hash before use.
 * Also bakes grades (sliders + look) into one LUT for preview and export, with a small cache.
 */
@Singleton
class LutLibrary @Inject constructor(
    @ApplicationContext private val context: Context,
) {
    private val root get() = File(context.filesDir, "luts").apply { mkdirs() }
    private val importDir get() = File(root, "imported").apply { mkdirs() }
    private val packDir get() = File(root, "packs/gmic").apply { mkdirs() }

    private data class PackItem(val entry: LutEntry, val path: String, val sha1: String, val size: Long)

    private val pack: Pair<LutPackInfo, List<PackItem>> by lazy { loadPack() }

    val packInfo: LutPackInfo get() = pack.first

    private val _version = MutableStateFlow(0)
    /** Bumps whenever entries change (import, delete, download). */
    val version: StateFlow<Int> = _version.asStateFlow()

    // ------------------------------------------------------------------ entries & search

    fun entries(): List<LutEntry> {
        val builtIn = BuiltInLooks.ALL.map { LutEntry(it.id, it.name, it.category, it.tags, LutSource.BUILTIN, it.description) }
        val imported = importDir.listFiles { f -> f.name.endsWith(".cube") }.orEmpty().sortedBy { it.lastModified() }.map { f ->
            val meta = readMeta(f)
            val name = meta.getProperty("name") ?: f.nameWithoutExtension
            LutEntry("import:${f.nameWithoutExtension}", name, "Imported", LutAdvisor.keywords(name) + "imported", LutSource.IMPORTED)
        }
        val packItems = pack.second.map { it.entry.copy(available = packFile(it.path).exists()) }
        return builtIn + imported + packItems
    }

    /** Case-insensitive search over names, categories and scene/mood tags ("beach sunset", "night", "film"). */
    fun search(query: String, source: LutSource? = null): List<LutEntry> {
        val all = entries().filter { source == null || it.source == source }
        val words = query.lowercase().split(Regex("\\s+")).filter { it.isNotBlank() }
        if (words.isEmpty()) return all
        val expanded = LutAdvisor.keywords(query)
        return all.map { e ->
            val hay = (e.name + " " + e.category + " " + e.tags.joinToString(" ")).lowercase()
            val hits = words.count { hay.contains(it) } + e.tags.count { it in expanded }
            e to hits
        }.filter { it.second > 0 }.sortedByDescending { it.second }.map { it.first }
    }

    // ------------------------------------------------------------------ loading & baking

    private val lutCache = object : LinkedHashMap<String, CubeLut>(16, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, CubeLut>?) = size > 12
    }
    private val bakeCache = object : LinkedHashMap<String, CubeLut>(16, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, CubeLut>?) = size > 24
    }

    /** The look's LUT, or null when unknown / not downloaded / unreadable. */
    @Synchronized
    fun load(id: String): CubeLut? {
        lutCache[id]?.let { return it }
        val lut = runCatching {
            when {
                id.startsWith("builtin:") -> BuiltInLooks.byId(id)?.toLut(ColorMath.BAKE_SIZE)
                id.startsWith("import:") -> File(importDir, id.removePrefix("import:") + ".cube").takeIf { it.exists() }?.let { CubeLut.parse(it.readText()) }
                id.startsWith("gmic:") -> pack.second.firstOrNull { it.entry.id == id }?.let { packFile(it.path) }?.takeIf { it.exists() }?.let { CubeLut.parse(it.readText()) }
                else -> null
            }
        }.onFailure { CineMindLogger.w("LUT $id unreadable: ${it.message}") }.getOrNull()
        if (lut != null) lutCache[id] = lut
        return lut
    }

    /** The whole grade as one LUT for the GPU, or null when it changes nothing (cached). */
    @Synchronized
    fun baked(grade: ColorGrade): CubeLut? {
        if (grade.isNeutral) return null
        val key = grade.encode()
        bakeCache[key]?.let { return it }
        val look = grade.lutId?.let { load(it) }
        val lut = ColorMath.bake(grade, look) ?: return null
        bakeCache[key] = lut
        return lut
    }

    /** Baked grades for clips, keyed by clip id (what preview and export need). */
    fun bakedForClips(grades: Map<String, String>): Map<String, CubeLut> =
        grades.mapNotNull { (id, text) -> baked(ColorGrade.decode(text))?.let { id to it } }.toMap()

    // ------------------------------------------------------------------ import

    /** Imports a `.cube` from the phone; returns the new entry or throws [LutFormatException] / IOException. */
    suspend fun importCube(uri: Uri, displayName: String?): LutEntry = withContext(Dispatchers.IO) {
        val bytes = context.contentResolver.openInputStream(uri)?.use { input ->
            val buf = input.readNBytesCompat(MAX_IMPORT_BYTES + 1)
            if (buf.size > MAX_IMPORT_BYTES) throw LutFormatException("The file is too large for a LUT (over 8 MB).")
            buf
        } ?: throw IOException("Couldn't open the file")
        val text = bytes.toString(Charsets.UTF_8)
        val lut = CubeLut.parse(text) // validates; throws with a reason
        val id = UUID.randomUUID().toString()
        val f = File(importDir, "$id.cube")
        f.writeText(text)
        val name = displayName?.substringBeforeLast('.')?.takeIf { it.isNotBlank() } ?: lut.title.ifBlank { "Imported LUT" }
        Properties().apply { setProperty("name", name) }.let { p -> File(importDir, "$id.properties").outputStream().use { p.store(it, null) } }
        _version.value++
        LutEntry("import:$id", name, "Imported", LutAdvisor.keywords(name) + "imported", LutSource.IMPORTED)
    }

    fun deleteImported(id: String) {
        val key = id.removePrefix("import:")
        File(importDir, "$key.cube").delete()
        File(importDir, "$key.properties").delete()
        synchronized(this) { lutCache.remove(id) }
        _version.value++
    }

    // ------------------------------------------------------------------ film pack

    fun isPack(id: String) = id.startsWith("gmic:")

    /** Downloads one pack LUT (~130 KB) from the pinned commit and checks its git blob hash. */
    suspend fun download(id: String): Unit = withContext(Dispatchers.IO) {
        val item = pack.second.firstOrNull { it.entry.id == id } ?: throw IOException("Unknown LUT")
        val target = packFile(item.path)
        if (target.exists()) return@withContext
        val url = URL(PACK_BASE.format(pack.first.commit) + item.path)
        val conn = (url.openConnection() as HttpURLConnection).apply { connectTimeout = 15_000; readTimeout = 20_000 }
        val bytes = try {
            if (conn.responseCode != 200) throw IOException("Download failed (HTTP ${conn.responseCode})")
            conn.inputStream.use { it.readNBytesCompat(MAX_IMPORT_BYTES) }
        } finally {
            conn.disconnect()
        }
        if (bytes.size.toLong() != item.size || gitBlobSha1(bytes) != item.sha1) {
            throw IOException("The downloaded LUT didn't match the catalogue (integrity check failed)")
        }
        CubeLut.parse(bytes.toString(Charsets.UTF_8)) // must be a valid LUT too
        target.parentFile?.mkdirs()
        val tmp = File(target.path + ".part")
        tmp.writeBytes(bytes)
        if (!tmp.renameTo(target)) throw IOException("Couldn't save the LUT")
        _version.value++
    }

    private fun packFile(path: String) = File(packDir, path.removePrefix("luts/"))

    private fun loadPack(): Pair<LutPackInfo, List<PackItem>> = runCatching {
        val json = JSONObject(context.assets.open("luts/gmic_film_pack.json").bufferedReader().use { it.readText() })
        val info = LutPackInfo(json.getString("pack"), json.getString("repo"), json.getString("commit"), json.getString("license"))
        val arr = json.getJSONArray("luts")
        val items = (0 until arr.length()).map { i ->
            val o = arr.getJSONObject(i)
            val tags = o.getJSONArray("tags").let { t -> (0 until t.length()).map { t.getString(it) } }.toSet()
            val name = o.getString("name")
            PackItem(
                LutEntry(o.getString("id"), name, o.getString("category"), tags + LutAdvisor.keywords(name).filter { it.length > 3 }, LutSource.PACK, available = false),
                o.getString("path"), o.getString("sha1"), o.getLong("size"),
            )
        }
        info to items
    }.getOrElse {
        CineMindLogger.w("LUT pack catalogue unreadable: ${it.message}")
        LutPackInfo("Film pack", "", "", "") to emptyList()
    }

    private fun readMeta(cube: File): Properties = Properties().apply {
        File(cube.parentFile, cube.nameWithoutExtension + ".properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
    }

    companion object {
        const val MAX_IMPORT_BYTES = 8 * 1024 * 1024
        const val PACK_BASE = "https://raw.githubusercontent.com/YahiaAngelo/Film-Luts/%s/"

        /** Git's blob id: SHA-1 of "blob <length>\0" + content (what the catalogue stores). */
        fun gitBlobSha1(bytes: ByteArray): String {
            val md = MessageDigest.getInstance("SHA-1")
            md.update("blob ${bytes.size}\u0000".toByteArray(Charsets.US_ASCII))
            md.update(bytes)
            return md.digest().joinToString("") { "%02x".format(it) }
        }
    }
}

private fun java.io.InputStream.readNBytesCompat(max: Int): ByteArray {
    val out = java.io.ByteArrayOutputStream()
    val buf = ByteArray(64 * 1024)
    var total = 0
    while (total < max) {
        val n = read(buf, 0, minOf(buf.size, max - total))
        if (n < 0) break
        out.write(buf, 0, n)
        total += n
    }
    return out.toByteArray()
}
