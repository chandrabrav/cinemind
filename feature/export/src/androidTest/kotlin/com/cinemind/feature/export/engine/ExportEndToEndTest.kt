/**
 * Renders a real mixed timeline on the device/emulator and inspects the MP4:
 * portrait video with audio → photo (fade in) → landscape 60 fps silent video (slide in).
 * Test media is generated by ffmpeg in CI (see .github/workflows/ci.yml).
 */
@RunWith(AndroidJUnit4::class)
class ExportEndToEndTest {

    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val context = instrumentation.targetContext

    private fun asset(name: String): File {
        val out = File(context.cacheDir, "e2e-$name")
        instrumentation.context.assets.open(name).use { input -> out.outputStream().use { input.copyTo(it) } }
        return out
    }

    private fun clip(id: String, inUs: Long, outUs: Long, type: ClipTransition = ClipTransition.CUT, ms: Long = 0) =
        Clip(id = id, trackId = "t", assetId = id, timelineInUs = 0, timelineOutUs = 0, sourceInUs = inUs, sourceOutUs = outUs,
            transitionInType = type.name, transitionInMs = ms)

    @Test
    fun exportsMixedTimelineWithTransitions() = runBlocking {
        val portrait = asset("portrait.mp4")
        val photo = asset("photo.jpg")
        val landscape = asset("landscape_silent.mp4")

        // [0, 2.0) portrait  [2.0, 3.0) photo (fade 800 ms)  [3.0, 4.5) landscape 0.5–2.0 s (slide 400 ms)
        val clips = TimelineEditing.relayout(
            listOf(
                clip("v1", 0, 2_000_000),
                clip("p", 0, 1_000_000, ClipTransition.FADE, 800),
                clip("v2", 500_000, 2_000_000, ClipTransition.SLIDE_LEFT, 400),
            ),
        )
        val sources = listOf(
            RenderSource(Uri.fromFile(portrait).toString(), isVideo = true, hasAudio = true, frameRate = 30f, durationUs = 2_000_000),
            RenderSource(Uri.fromFile(photo).toString(), isVideo = false, hasAudio = false, frameRate = 0f, durationUs = 0),
            RenderSource(Uri.fromFile(landscape).toString(), isVideo = true, hasAudio = false, frameRate = 60f, durationUs = 2_000_000),
        )
        val out = File(context.cacheDir, "e2e-out.mp4").apply { delete() }

        val progressScope = CoroutineScope(SupervisorJob() + Dispatchers.Main)
        withContext(Dispatchers.Main) {
            val renderer = TimelineRenderer(context)
            val composition = renderer.buildComposition(clips.zip(sources), OutputSize(720, 1280), fps = 30)
            renderer.render(composition, out, videoBitrateBps = 4_000_000, progressScope = progressScope)
        }
        progressScope.cancel()

        assertTrue("output written", out.exists() && out.length() > 10_000)

        val r = MediaMetadataRetriever()
        try {
            r.setDataSource(out.absolutePath)
            val durationMs = r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_DURATION)!!.toLong()
            assertTrue("duration ~4.5 s, was $durationMs ms", durationMs in 4_200..4_800)
            assertEquals("yes", r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_HAS_VIDEO))
            assertEquals("yes", r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_HAS_AUDIO))
            // Media3 may encode portrait as landscape + a 90° rotation flag; players show it upright.
            val w = r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_VIDEO_WIDTH)!!.toInt()
            val h = r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_VIDEO_HEIGHT)!!.toInt()
            val rotation = r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_VIDEO_ROTATION)?.toIntOrNull() ?: 0
            val (shownW, shownH) = if (rotation % 180 != 0) h to w else w to h
            assertEquals("displayed width (raw ${w}x$h, rotation $rotation)", 720, shownW)
            assertEquals("displayed height (raw ${w}x$h, rotation $rotation)", 1280, shownH)

            // Fade: the cut at 2.0 s must be (near) black, while the middle of each side is not.
            // This also proves effects see composition time (the assumption in TimelineRenderer).
            val midFirst = luma(r, 1_000_000)
            val atCut = luma(r, 2_000_000)
            val midPhoto = luma(r, 2_600_000)
            val midLast = luma(r, 3_900_000)
            assertTrue("first clip visible ($midFirst)", midFirst > 0.15f)
            assertTrue("photo visible after its fade-in ($midPhoto)", midPhoto > 0.15f)
            assertTrue("last clip visible ($midLast)", midLast > 0.15f)
            assertTrue("dips to black at the cut ($atCut vs $midFirst)", atCut < midFirst * 0.35f)
        } finally {
            r.release()
        }
    }

    @Test
    fun exportsWithLoopingMusicAndLowerOriginalSound() = runBlocking {
        val photo = asset("photo.jpg")
        val landscape = asset("landscape_silent.mp4")
        val song = asset("music.m4a") // 3 s tone; the 5 s video below needs it looped

        val clips = TimelineEditing.relayout(
            listOf(clip("p", 0, 3_000_000), clip("v", 0, 2_000_000, ClipTransition.FADE, 500)),
        )
        val sources = listOf(
            RenderSource(Uri.fromFile(photo).toString(), isVideo = false, hasAudio = false, frameRate = 0f, durationUs = 0),
            RenderSource(Uri.fromFile(landscape).toString(), isVideo = true, hasAudio = false, frameRate = 60f, durationUs = 2_000_000),
        )
        val music = RenderMusic(Uri.fromFile(song).toString(), durationUs = 3_000_000, startOffsetUs = 1_000_000,
            volume = 0.8f, fadeInUs = 500_000, fadeOutUs = 800_000)
        val out = File(context.cacheDir, "e2e-music.mp4").apply { delete() }

        val progressScope = CoroutineScope(SupervisorJob() + Dispatchers.Main)
        withContext(Dispatchers.Main) {
            val renderer = TimelineRenderer(context)
            val composition = renderer.buildComposition(clips.zip(sources), OutputSize(720, 1280), fps = 30, music = music, originalVolume = 0.3f)
            renderer.render(composition, out, videoBitrateBps = 3_000_000, progressScope = progressScope)
        }
        progressScope.cancel()

        val r = MediaMetadataRetriever()
        try {
            r.setDataSource(out.absolutePath)
            val durationMs = r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_DURATION)!!.toLong()
            // Music must not stretch the video: it is cut to the 5 s timeline.
            assertTrue("duration ~5 s, was $durationMs ms", durationMs in 4_700..5_300)
            assertEquals("yes", r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_HAS_AUDIO))
            assertEquals("yes", r.extractMetadata(MediaMetadataRetriever.METADATA_KEY_HAS_VIDEO))
        } finally {
            r.release()
        }
    }

    /**
     * Captions are burned in by the same painter as the preview: a white caption box must appear in
     * its band only while the caption is on, on an otherwise black video, at the right times.
     */
    @Test
    fun burnsInCaptionsAtTheirTimes() = runBlocking {
        val black = asset("black.mp4")
        val clips = TimelineEditing.relayout(listOf(clip("b", 0, 2_000_000)))
        val sources = listOf(RenderSource(Uri.fromFile(black).toString(), isVideo = true, hasAudio = false, frameRate = 30f, durationUs = 2_000_000))
        val style = com.cinemind.core.domain.captions.CaptionStyle(
            projectId = "p",
            mode = com.cinemind.core.domain.captions.CaptionMode.SENTENCE.name,
            animation = com.cinemind.core.domain.captions.CaptionAnimation.NONE.name,
            karaoke = false,
            backgroundColor = 0xFFFFFFFF.toInt(),
            backgroundOpacity = 1f,
            positionY = 0.5f,
            size = 0.08f,
        )
        val caption = com.cinemind.core.domain.captions.Caption(
            projectId = "p", startUs = 200_000, endUs = 1_000_000, text = "Bhai, yeh jagah sach mein bahut beautiful hai!",
        )
        val out = File(context.cacheDir, "e2e-captions.mp4").apply { delete() }
        val progressScope = CoroutineScope(SupervisorJob() + Dispatchers.Main)
        withContext(Dispatchers.Main) {
            val renderer = TimelineRenderer(context)
            val composition = renderer.buildComposition(
                clips.zip(sources), OutputSize(720, 1280), fps = 30,
                captions = RenderCaptions(listOf(caption), style),
            )
            renderer.render(composition, out, videoBitrateBps = 4_000_000, progressScope = progressScope)
        }
        progressScope.cancel()

        val r = MediaMetadataRetriever()
        try {
            r.setDataSource(out.absolutePath)
            val during = r.getFrameAtTime(600_000, MediaMetadataRetriever.OPTION_CLOSEST)!!
            saveForReview(during, "export_caption_frame")
            val band = bandLuma(during, 0.42f, 0.58f)
            val top = bandLuma(during, 0.05f, 0.2f)
            val after = bandLuma(r.getFrameAtTime(1_500_000, MediaMetadataRetriever.OPTION_CLOSEST)!!, 0.42f, 0.58f)
            val before = bandLuma(r.getFrameAtTime(0, MediaMetadataRetriever.OPTION_CLOSEST)!!, 0.42f, 0.58f)
            assertTrue("caption box visible in its band ($band)", band > 0.25f)
            assertTrue("nothing drawn outside the caption ($top)", top < 0.06f)
            assertTrue("caption gone after its end ($after)", after < 0.06f)
            assertTrue("caption not shown before its start ($before)", before < 0.06f)
        } finally {
            r.release()
        }
    }

    /** Mean luma (0..1) of the horizontal band between [y0] and [y1] (fractions of the height). */
    private fun bandLuma(raw: Bitmap, y0: Float, y1: Float): Float {
        // Media3 may store portrait as landscape + rotation flag; measure the upright picture.
        val frame = if (raw.width > raw.height) {
            Bitmap.createBitmap(raw, 0, 0, raw.width, raw.height, android.graphics.Matrix().apply { postRotate(90f) }, false)
        } else {
            raw
        }
        val small = Bitmap.createScaledBitmap(frame, 72, 128, true)
        val from = (small.height * y0).toInt()
        val to = (small.height * y1).toInt()
        val px = IntArray(small.width * (to - from))
        small.getPixels(px, 0, small.width, 0, from, small.width, to - from)
        val mean = px.map { c -> (299 * ((c shr 16) and 0xFF) + 587 * ((c shr 8) and 0xFF) + 114 * (c and 0xFF)) / 1000 }.average()
        return (mean / 255.0).toFloat()
    }

    /** Saved next to the screenshots so a person can look at the rendered caption. */
    private fun saveForReview(bitmap: Bitmap, name: String) {
        val dir = androidx.test.platform.app.InstrumentationRegistry.getArguments().getString("additionalTestOutputDir")
            ?.let { File(it) } ?: context.getExternalFilesDir(null) ?: return
        runCatching {
            dir.mkdirs()
            File(dir, "$name.png").outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
        }
    }

    private fun luma(r: MediaMetadataRetriever, timeUs: Long): Float {
        val frame: Bitmap = r.getFrameAtTime(timeUs, MediaMetadataRetriever.OPTION_CLOSEST)
            ?: error("no frame at $timeUs")
        val small = Bitmap.createScaledBitmap(frame, 36, 64, true)
        val px = IntArray(small.width * small.height)
        small.getPixels(px, 0, small.width, 0, 0, small.width, small.height)
        val mean = px.map { c -> (299 * ((c shr 16) and 0xFF) + 587 * ((c shr 8) and 0xFF) + 114 * (c and 0xFF)) / 1000 }.average()
        return (mean / 255.0).toFloat()
    }
}
